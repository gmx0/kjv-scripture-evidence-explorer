import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {bestLetterPattern,morphologyBetween,wordFeatures} from "../dist/algorithm.js";

const rows=(await readFile(new URL("../dist/data/kjv/verses.jsonl",import.meta.url),"utf8")).trim().split("\n").map(JSON.parse);
const bounds=JSON.parse(await readFile(new URL("../dist/data/kjv/corpus-bounds.json",import.meta.url),"utf8")).bounds;
const words=new Set(rows.flatMap(row=>row.displayText.toLowerCase().match(/[a-z]+/g)||[]));
assert(words.has("freewill"));
assert(words.has("free"));
assert(words.has("will"));
assert(words.has("selfwilled"));
const freewill=wordFeatures("freewill",words);
assert(freewill.components.has("free")&&freewill.components.has("will"));
assert.equal(morphologyBetween("freewill","free",words,()=>1).kind,"shared_initial_segment");
assert.equal(morphologyBetween("freewill","selfwilled",words,()=>1).kind,"shared_internal_segment");
assert(bestLetterPattern("freewill","selfwilled",()=>1,words.size).score>bestLetterPattern("free","work",()=>1,words.size).score);
const tokenize=text=>[...text.matchAll(/[\p{L}\p{N}]+(?:['’][\p{L}\p{N}]+)*/gu)].map(match=>match[0].normalize("NFC").toLowerCase().replaceAll("’", "'"));
const tokenized=rows.map(row=>tokenize(row.displayText)),frequencies=new Map();
for(const tokens of tokenized)for(const word of tokens)frequencies.set(word,(frequencies.get(word)||0)+1);
assert.equal(frequencies.get("neighbour"),107);
assert.equal(frequencies.get("neighbours"),22);
assert.equal(tokenized.reduce((sum,tokens)=>sum+tokens.length,0),bounds.totalTokens);
assert.equal(frequencies.size,bounds.vocabulary);
assert.equal(Math.max(...tokenized.map(tokens=>tokens.length)),bounds.verseWords.max);
assert.equal(Math.max(...[...frequencies.keys()].map(word=>[...word].filter(char=>/\p{L}/u.test(char)).length)),bounds.wordLetters.max);
assert.equal(Math.max(...frequencies.values()),bounds.corpusFrequency.max);
const displayGroups=new Map();for(const row of rows)displayGroups.set(row.displayText,(displayGroups.get(row.displayText)||0)+1);
assert.equal([...displayGroups.values()].filter(count=>count>1).length,bounds.exactRepeatedText.groups);
assert.equal(Math.max(...displayGroups.values()),bounds.exactRepeatedText.maximumMultiplicity);
console.log(`corpus smoke tests passed (${rows.length} verses, ${words.size} word forms)`);
