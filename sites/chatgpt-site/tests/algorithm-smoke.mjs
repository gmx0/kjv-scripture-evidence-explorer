import assert from "node:assert/strict";
import {ALGORITHM_VERSION,bestLetterPattern,caseEvidence,corpusRarity,exactWordEvidence,finalEvidenceScore,lemmaCandidates,morphologyBetween,proximitySelfRecursiveScore,repetitionValue,textualSelfRecursiveScore,totalScore,wordFeatures,wordLengthValue} from "../dist/algorithm.js";

assert.equal(ALGORITHM_VERSION,"2.7.0");
const vocabulary=new Set(["free","will","self","freewill","selfwill","selfwilled"]);
assert.deepEqual(wordFeatures("freewill",vocabulary).components,new Set(["free","will"]));
assert(lemmaCandidates("selfwilled").includes("selfwill"));
assert.equal(morphologyBetween("freewill","selfwill",vocabulary,()=>({rarity:1,frequency:1,independentTokenFrequency:1})).kind,"shared_terminal_segment");
assert.doesNotThrow(()=>morphologyBetween("selfwilled","selfwill",vocabulary,()=>1));
assert.equal(morphologyBetween("free-will","freewill",vocabulary,()=>1).kind,"punctuation_folded_form");
assert.equal(morphologyBetween("man's","man",vocabulary,()=>1).kind,"punctuation_component");
const willSegment=morphologyBetween("freewill","selfwill",vocabulary,()=>({rarity:.8,frequency:2,independentTokenFrequency:10}));
const edSegment=morphologyBetween("commanded","revealed",vocabulary,()=>({rarity:.2,frequency:100,independentTokenFrequency:0}));
assert.equal(edSegment.kind,"shared_terminal_segment");
assert.deepEqual(edSegment.shared,["ed"]);
assert(willSegment.score>edSegment.score&&edSegment.score>0);
assert(corpusRarity(1000,1)>corpusRarity(1000,100));
assert(wordLengthValue("will")>wordLengthValue("the"));
assert(exactWordEvidence("will",.5)>exactWordEvidence("the",.5));
assert(exactWordEvidence("rareword",.9)>exactWordEvidence("the",.1));
assert.equal(wordLengthValue("mahershalalhashbaz",18),1);
assert.equal(corpusRarity(63919,1),1);
assert(corpusRarity(63919,63919)>0);
assert.equal(repetitionValue(18,18),1);
const four=bestLetterPattern("freewill","selfwill",()=>1,vocabulary.size);
const one=bestLetterPattern("free","work",()=>1,vocabulary.size);
assert.equal(four.fragment,"fewill");
assert(four.score>one.score&&one.score>0);
assert(caseEvidence("Spirit","Spirit",0).score>caseEvidence("Spirit","spirit",0).score);
assert.equal(caseEvidence("And","and",2).score,caseEvidence("And","and",0).score);
assert.equal(totalScore({jaccard:1,phrase:1,rare:1,order:1,capitalization:1,morphology:1,letterPattern:1,crossReference:1,proximity:1}),1);
const textual=textualSelfRecursiveScore({jaccard:1,phrase:0,rare:1,order:0,capitalization:0,morphology:0,letterPattern:0});
assert.equal(textual.groups.word,1);
assert(textual.score>.8);
const life=textualSelfRecursiveScore({jaccard:.10,rare:.10,morphology:0,phrase:0,letterPattern:0,capitalization:0}).score;
const everlasting=textualSelfRecursiveScore({jaccard:.20,rare:.20,morphology:0,phrase:0,letterPattern:0,capitalization:0}).score;
const separated=textualSelfRecursiveScore({jaccard:.30,rare:.25,morphology:0,phrase:0,letterPattern:0,capitalization:0}).score;
const continuous=textualSelfRecursiveScore({jaccard:.30,rare:.25,morphology:0,phrase:.50,letterPattern:0,capitalization:0}).score;
assert(life<everlasting&&everlasting<separated&&separated<continuous);
const punctuationVariant=textualSelfRecursiveScore({jaccard:.30,rare:.25,morphology:0,phrase:0,phraseVariant:.40,letterPattern:0,capitalization:0});
assert(punctuationVariant.score>separated&&punctuationVariant.groups.line===0);
assert.equal(proximitySelfRecursiveScore({word:1,book:1,letter:1,verse:1,chapter:1,testament:1}),1);
assert(proximitySelfRecursiveScore({word:1})>.78);
assert.equal(finalEvidenceScore(1,1),1);
assert(finalEvidenceScore(.5,1)>finalEvidenceScore(.5,0));
assert.equal(Math.round((finalEvidenceScore(.5,1)-finalEvidenceScore(.5,0))*1e6),73590);
console.log("algorithm smoke tests passed");
